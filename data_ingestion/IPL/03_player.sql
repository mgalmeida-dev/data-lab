-- Creating the table
CREATE TABLE ipl.player 
(
    player_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_name VARCHAR(100) NOT NULL UNIQUE,
    team_id INTEGER NOT NULL,
    FOREIGN KEY (team_id) REFERENCES ipl.team(team_id)
);

